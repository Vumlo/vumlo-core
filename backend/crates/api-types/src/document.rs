/// The client builds the embed address from a fixed template; the server stores no URL.
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize, ToSchema,
)]
#[serde(rename_all = "lowercase")]
pub enum VideoProvider {
    Youtube,
    Vimeo,
}

names!(VideoProvider { Youtube => "youtube", Vimeo => "vimeo" });

/// A run of inline content.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum Inline {
    Text(TextRun),
    Link {
        /// http or https, at most 2048 characters.
        href: String,
        content: Vec<LinkRun>,
    },
    /// A formula inside a line, as LaTeX.
    Math {
        source: String,
    },
}

/// What a link may contain: text only.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum LinkRun {
    Text(TextRun),
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
pub struct TextRun {
    pub text: String,
    #[serde(default, skip_serializing_if = "Styles::is_plain")]
    pub styles: Styles,
}

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
pub struct Styles {
    #[serde(default, skip_serializing_if = "is_false")]
    pub bold: bool,
    #[serde(default, skip_serializing_if = "is_false")]
    pub italic: bool,
    #[serde(default, skip_serializing_if = "is_false")]
    pub strike: bool,
    /// Inline code.
    #[serde(default, skip_serializing_if = "is_false")]
    pub code: bool,
}

fn is_false(value: &bool) -> bool {
    !*value
}

impl Styles {
    pub fn is_plain(&self) -> bool {
        *self == Self::default()
    }
}

/// What a place of the editor can offer. A profile is a set of features (ADR-0025).
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize, ToSchema,
)]
#[serde(rename_all = "snake_case")]
pub enum Feature {
    Headings,
    TextStyles,
    Links,
    Lists,
    Quote,
    Divider,
    Table,
    Code,
    Math,
    Mermaid,
    Video,
}

names!(Feature {
    Headings => "headings", TextStyles => "text_styles", Links => "links", Lists => "lists",
    Quote => "quote", Divider => "divider", Table => "table", Code => "code", Math => "math",
    Mermaid => "mermaid", Video => "video",
});

#[derive(
    Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize, ToSchema,
)]
#[serde(rename_all = "snake_case")]
pub enum ProfileName {
    Full,
    Question,
    Option,
    Student,
}

names!(ProfileName { Full => "full", Question => "question", Option => "option", Student => "student" });

/// The numeric limits a document is validated against.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
pub struct DocumentLimits {
    pub max_document_bytes: u32,
    pub max_depth: u32,
    pub max_table_rows: u32,
    pub max_table_columns: u32,
    pub max_code_bytes: u32,
    pub max_formula_bytes: u32,
    pub max_href_chars: u32,
}

/// One profile as the server enforces it.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
pub struct EditorProfile {
    pub name: ProfileName,
    /// The features this profile allows after the institution's config narrowed it.
    pub features: Vec<Feature>,
    /// True when a document of this profile is exactly one block, without children.
    pub single_block: bool,
    pub limits: DocumentLimits,
}

/// What the editor needs to build its toolbar: the effective profiles and video providers.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
pub struct EditorProfiles {
    pub profiles: Vec<EditorProfile>,
    /// The providers a video block may name; empty when video is switched off.
    pub video_providers: Vec<VideoProvider>,
}

