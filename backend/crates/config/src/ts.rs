//! TypeScript types from the JSON Schema of [`ClientConfig`]. Only the shapes that struct uses are
//! understood (objects, maps, arrays, strings, numbers, booleans, string enums, optional values);
//! anything else is an error, so a new kind of field cannot silently produce a wrong type.

use serde_json::Value;

use crate::client::ClientConfig;
use crate::schema;

/// `client-config.d.ts`: `ClientConfig` and its parts.
pub fn client_config_types() -> Result<String, String> {
    let mut settings = schemars::generate::SchemaSettings::draft2020_12();
    settings.inline_subschemas = true;
    let schema = schema::schema_of::<ClientConfig>(settings.into_generator());
    let body = ts_type(&schema, 0)?;
    Ok(format!(
        "// Generated by `vumlo-cli brand apply` from the configuration schema. Do not edit.\n\
         export type ClientConfig = {body};\n"
    ))
}

fn ts_type(node: &Value, depth: usize) -> Result<String, String> {
    if let Some(values) = node.get("enum").and_then(Value::as_array) {
        return literals(values);
    }
    if let Some(value) = node.get("const") {
        return literals(std::slice::from_ref(value));
    }
    for key in ["oneOf", "anyOf"] {
        if let Some(members) = node.get(key).and_then(Value::as_array) {
            let parts: Result<Vec<_>, _> = members.iter().map(|m| ts_type(m, depth)).collect();
            return Ok(parts?.join(" | "));
        }
    }
    let types: Vec<&str> = match node.get("type") {
        Some(Value::String(one)) => vec![one.as_str()],
        Some(Value::Array(many)) => many.iter().filter_map(Value::as_str).collect(),
        _ => return Err(format!("no type in {node}")),
    };
    let parts: Result<Vec<_>, _> = types.iter().map(|t| one_type(node, t, depth)).collect();
    Ok(parts?.join(" | "))
}

fn one_type(node: &Value, kind: &str, depth: usize) -> Result<String, String> {
    match kind {
        "string" => Ok("string".to_owned()),
        "integer" | "number" => Ok("number".to_owned()),
        "boolean" => Ok("boolean".to_owned()),
        "null" => Ok("null".to_owned()),
        "array" => {
            let items = node.get("items").ok_or("an array without items")?;
            Ok(format!("({})[]", ts_type(items, depth)?))
        }
        "object" => object(node, depth),
        other => Err(format!("unsupported schema type `{other}`")),
    }
}

fn object(node: &Value, depth: usize) -> Result<String, String> {
    let pad = "  ".repeat(depth + 1);
    if let Some(props) = node.get("properties").and_then(Value::as_object) {
        let required: Vec<&str> = node
            .get("required")
            .and_then(Value::as_array)
            .map(|r| r.iter().filter_map(Value::as_str).collect())
            .unwrap_or_default();
        let mut out = String::from("{\n");
        for (name, child) in props {
            if let Some(doc) = child.get("description").and_then(Value::as_str) {
                out.push_str(&format!("{pad}/** {} */\n", doc.replace("*/", "* /")));
            }
            let optional = if required.contains(&name.as_str()) {
                ""
            } else {
                "?"
            };
            out.push_str(&format!(
                "{pad}{name}{optional}: {};\n",
                ts_type(child, depth + 1)?
            ));
        }
        out.push_str(&format!("{}}}", "  ".repeat(depth)));
        return Ok(out);
    }
    if let Some(extra) = node.get("additionalProperties").filter(|v| v.is_object()) {
        return Ok(format!("{{ [name: string]: {} }}", ts_type(extra, depth)?));
    }
    Err(format!("an object without properties: {node}"))
}

fn literals(values: &[Value]) -> Result<String, String> {
    let parts: Result<Vec<_>, _> = values
        .iter()
        .map(|v| match v {
            Value::String(s) => Ok(format!("{s:?}")),
            other => Err(format!("unsupported enum value {other}")),
        })
        .collect();
    Ok(parts?.join(" | "))
}

