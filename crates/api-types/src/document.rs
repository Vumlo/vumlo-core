//! Block documents (ADR-0025, ADR-0027): the wire format and the storage format are the same.
//! `content` validates a JSON value into a [`Document`] and stores its serialization.

use serde::{Deserialize, Serialize};
use utoipa::ToSchema;
use uuid::Uuid;

/// `ALL`, `as_str` and `from_name` for an enum whose serde names are these literals.
macro_rules! names {
    ($name:ident { $($variant:ident => $text:literal),+ $(,)? }) => {
        impl $name {
            pub const ALL: &'static [Self] = &[$(Self::$variant),+];

            pub fn as_str(self) -> &'static str {
                match self { $(Self::$variant => $text),+ }
            }

            pub fn from_name(name: &str) -> Option<Self> {
                match name { $($text => Some(Self::$variant),)+ _ => None }
            }
        }
    };
}

/// A block document. `attachments` must be empty for now and is optional on input.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
pub struct Document {
    /// The format version, always 1.
    pub v: u32,
    pub blocks: Vec<Block>,
    #[serde(default)]
    pub attachments: Vec<Uuid>,
}

impl Document {
    /// The document of an item that has no text yet.
    pub fn empty() -> Self {
        Self {
            v: 1,
            blocks: Vec::new(),
            attachments: Vec::new(),
        }
    }
}

/// One block. `id` is 1 to 64 characters from `[A-Za-z0-9_-]`, unique in the document and
/// generated by the client. `props`, `content` and `children` are left out when empty.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum Block {
    Paragraph {
        id: String,
        #[serde(default, skip_serializing_if = "Vec::is_empty")]
        content: Vec<Inline>,
    },
    Quote {
        id: String,
        #[serde(default, skip_serializing_if = "Vec::is_empty")]
        content: Vec<Inline>,
    },
    Heading {
        id: String,
        props: HeadingProps,
        #[serde(default, skip_serializing_if = "Vec::is_empty")]
        content: Vec<Inline>,
    },
    BulletedListItem {
        id: String,
        #[serde(default, skip_serializing_if = "Vec::is_empty")]
        content: Vec<Inline>,
        #[serde(default, skip_serializing_if = "Vec::is_empty")]
        #[schema(no_recursion)]
        children: Vec<Block>,
    },
    NumberedListItem {
        id: String,
        #[serde(default, skip_serializing_if = "Vec::is_empty")]
        content: Vec<Inline>,
        #[serde(default, skip_serializing_if = "Vec::is_empty")]
        #[schema(no_recursion)]
        children: Vec<Block>,
    },
    CheckListItem {
        id: String,
        props: CheckProps,
        #[serde(default, skip_serializing_if = "Vec::is_empty")]
        content: Vec<Inline>,
        #[serde(default, skip_serializing_if = "Vec::is_empty")]
        #[schema(no_recursion)]
        children: Vec<Block>,
    },
    Divider {
        id: String,
    },
    Table {
        id: String,
        props: TableProps,
    },
    Code {
        id: String,
        props: CodeProps,
    },
    /// A LaTeX formula on its own line.
    Math {
        id: String,
        props: SourceProps,
    },
    /// A Mermaid diagram.
    Mermaid {
        id: String,
        props: SourceProps,
    },
    Video {
        id: String,
        props: VideoProps,
    },
}

impl Block {
    pub fn id(&self) -> &str {
        match self {
            Self::Paragraph { id, .. }
            | Self::Quote { id, .. }
            | Self::Heading { id, .. }
            | Self::BulletedListItem { id, .. }
            | Self::NumberedListItem { id, .. }
            | Self::CheckListItem { id, .. }
            | Self::Divider { id }
            | Self::Table { id, .. }
            | Self::Code { id, .. }
            | Self::Math { id, .. }
            | Self::Mermaid { id, .. }
            | Self::Video { id, .. } => id,
        }
    }

    /// The inline text of the block, if its type has any.
    pub fn content(&self) -> &[Inline] {
        match self {
            Self::Paragraph { content, .. }
            | Self::Quote { content, .. }
            | Self::Heading { content, .. }
            | Self::BulletedListItem { content, .. }
            | Self::NumberedListItem { content, .. }
            | Self::CheckListItem { content, .. } => content,
            _ => &[],
        }
    }

    /// The nested blocks of a list item.
    pub fn children(&self) -> &[Block] {
        match self {
            Self::BulletedListItem { children, .. }
            | Self::NumberedListItem { children, .. }
            | Self::CheckListItem { children, .. } => children,
            _ => &[],
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
pub struct HeadingProps {
    /// 1, 2 or 3.
    pub level: u8,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
pub struct CheckProps {
    pub checked: bool,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
pub struct TableProps {
    pub header_row: bool,
    /// Rows of cells; a cell is a line of inline runs. All rows have the same number of cells.
    pub rows: Vec<Vec<Vec<Inline>>>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
pub struct CodeProps {
    /// A language outside the list is stored as `text`.
    pub language: CodeLanguage,
    /// Plain text; the client highlights it.
    pub source: String,
}

/// The source of a formula or a diagram, as plain text. The server never renders it.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
pub struct SourceProps {
    pub source: String,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
pub struct VideoProps {
    pub provider: VideoProvider,
    /// A YouTube id is 11 characters from `[A-Za-z0-9_-]`; a Vimeo id is 1 to 12 digits.
    pub video_id: String,
}

